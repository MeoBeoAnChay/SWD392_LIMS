/* Upgrade the original basic stocktaking tables to assigned-and-approved workflow. Safe to run repeatedly. */
IF COL_LENGTH('INVENTORY_CHECKS','AssignedTo') IS NULL ALTER TABLE INVENTORY_CHECKS ADD AssignedTo INT NULL;
IF COL_LENGTH('INVENTORY_CHECKS','LocationFilter') IS NULL ALTER TABLE INVENTORY_CHECKS ADD LocationFilter NVARCHAR(50) NULL;
IF COL_LENGTH('INVENTORY_CHECKS','ApprovedBy') IS NULL ALTER TABLE INVENTORY_CHECKS ADD ApprovedBy INT NULL;
IF COL_LENGTH('INVENTORY_CHECKS','ApprovedDate') IS NULL ALTER TABLE INVENTORY_CHECKS ADD ApprovedDate DATETIME NULL;
IF COL_LENGTH('INVENTORY_CHECKS','CancelReason') IS NULL ALTER TABLE INVENTORY_CHECKS ADD CancelReason NVARCHAR(255) NULL;
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name='FK_InventoryChecks_AssignedTo')
    ALTER TABLE INVENTORY_CHECKS ADD CONSTRAINT FK_InventoryChecks_AssignedTo FOREIGN KEY (AssignedTo) REFERENCES USERS(UserID);
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name='FK_InventoryChecks_ApprovedBy')
    ALTER TABLE INVENTORY_CHECKS ADD CONSTRAINT FK_InventoryChecks_ApprovedBy FOREIGN KEY (ApprovedBy) REFERENCES USERS(UserID);

IF COL_LENGTH('INVENTORY_CHECK_DETAILS','ProductID') IS NULL ALTER TABLE INVENTORY_CHECK_DETAILS ADD ProductID INT NULL;
IF COL_LENGTH('INVENTORY_CHECK_DETAILS','SerialNumber') IS NULL ALTER TABLE INVENTORY_CHECK_DETAILS ADD SerialNumber NVARCHAR(100) NULL;
IF COL_LENGTH('INVENTORY_CHECK_DETAILS','SystemLocation') IS NULL ALTER TABLE INVENTORY_CHECK_DETAILS ADD SystemLocation NVARCHAR(50) NULL;
IF COL_LENGTH('INVENTORY_CHECK_DETAILS','ActualLocation') IS NULL ALTER TABLE INVENTORY_CHECK_DETAILS ADD ActualLocation NVARCHAR(50) NULL;
IF COL_LENGTH('INVENTORY_CHECK_DETAILS','IsCounted') IS NULL ALTER TABLE INVENTORY_CHECK_DETAILS ADD IsCounted BIT NOT NULL CONSTRAINT DF_ICD_IsCounted DEFAULT 0;
IF COL_LENGTH('INVENTORY_CHECK_DETAILS','DiscrepancyReason') IS NULL ALTER TABLE INVENTORY_CHECK_DETAILS ADD DiscrepancyReason NVARCHAR(255) NULL;
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('INVENTORY_CHECK_DETAILS') AND name='InventoryID' AND is_nullable=0)
    ALTER TABLE INVENTORY_CHECK_DETAILS ALTER COLUMN InventoryID INT NULL;
GO
UPDATE d SET d.ProductID=i.ProductID,d.SerialNumber=i.SerialNumber,d.SystemLocation=i.Location,
    d.ActualLocation=COALESCE(d.ActualLocation,i.Location),d.IsCounted=1
FROM INVENTORY_CHECK_DETAILS d JOIN INVENTORY i ON i.InventoryID=d.InventoryID
WHERE d.ProductID IS NULL OR d.SerialNumber IS NULL OR d.SystemLocation IS NULL;
GO
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('INVENTORY_CHECK_DETAILS') AND name='SystemStatus' AND is_nullable=0)
    ALTER TABLE INVENTORY_CHECK_DETAILS ALTER COLUMN SystemStatus NVARCHAR(30) NULL;
IF EXISTS (SELECT 1 FROM sys.columns WHERE object_id=OBJECT_ID('INVENTORY_CHECK_DETAILS') AND name='ActualStatus' AND is_nullable=0)
    ALTER TABLE INVENTORY_CHECK_DETAILS ALTER COLUMN ActualStatus NVARCHAR(30) NULL;
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name='FK_ICD_Products')
    ALTER TABLE INVENTORY_CHECK_DETAILS ADD CONSTRAINT FK_ICD_Products FOREIGN KEY (ProductID) REFERENCES PRODUCTS(ProductID);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID('INVENTORY_CHECK_DETAILS') AND name='UQ_InventoryCheckDetails_Serial')
    CREATE UNIQUE INDEX UQ_InventoryCheckDetails_Serial ON INVENTORY_CHECK_DETAILS(CheckID,SerialNumber);
GO
