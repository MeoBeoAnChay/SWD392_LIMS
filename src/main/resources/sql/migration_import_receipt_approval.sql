-- Adds manager review and paper-signature capture to warehouse import receipts.
IF COL_LENGTH('IMPORT_RECEIPTS', 'ApprovedBy') IS NULL
    ALTER TABLE IMPORT_RECEIPTS ADD ApprovedBy INT NULL;
GO

IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = 'FK_ImportReceipts_ApprovedBy')
    ALTER TABLE IMPORT_RECEIPTS ADD CONSTRAINT FK_ImportReceipts_ApprovedBy FOREIGN KEY (ApprovedBy) REFERENCES USERS(UserID);
GO

IF COL_LENGTH('IMPORT_RECEIPTS', 'ApprovedDate') IS NULL
    ALTER TABLE IMPORT_RECEIPTS ADD ApprovedDate DATETIME NULL;
GO

IF COL_LENGTH('IMPORT_RECEIPTS', 'CancelReason') IS NULL
    ALTER TABLE IMPORT_RECEIPTS ADD CancelReason NVARCHAR(255) NULL;
GO

IF COL_LENGTH('IMPORT_RECEIPTS', 'PaperSigned') IS NULL
    ALTER TABLE IMPORT_RECEIPTS ADD PaperSigned BIT NOT NULL CONSTRAINT DF_ImportReceipts_PaperSigned DEFAULT 0;
GO

IF COL_LENGTH('IMPORT_RECEIPTS', 'PaperSignedAt') IS NULL
    ALTER TABLE IMPORT_RECEIPTS ADD PaperSignedAt DATETIME NULL;
GO
